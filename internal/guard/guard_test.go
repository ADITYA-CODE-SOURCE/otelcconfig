func writeFixture(t *testing.T, name, content string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	return dir
}

func TestRunFlagsViolations(t *testing.T) {
	dir := writeFixture(t, "hook.go", `package hook

import (
	"os"

	"gopkg.in/yaml.v3"

	"github.com/ADITYA-CODE-SOURCE/otelcconfig/runtime"
)

func init() {
	runtime.Register(runtime.ConfigSnapshot{})
}

func Read() string {
	_ = runtime.NetHTTPClient()
	_ = os.Getenv("OTEL_GO_ENABLED_INSTRUMENTATIONS")
	_ = yaml.Unmarshal
	return ""
}
`)

	diags, err := Run([]string{dir})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	got := map[string]bool{}
	for _, d := range diags {
		got[d.Message] = true
	}
	for _, want := range []string{
		"runtime.Register is reserved for generated baked configuration; hooks must not replace the snapshot",
		"option value \"OTEL_GO_ENABLED_INSTRUMENTATIONS\" must come from the baked runtime configuration, not the environment",
		"hooks must not parse YAML at runtime; configuration is baked at build time",
	} {
		if !got[want] {
			t.Errorf("missing diagnostic: %v\ngot: %v", want, got)
		}
	}
}

func TestRunAllowsGeneratedRegister(t *testing.T) {
	dir := writeFixture(t, "baked.go", "// Code generated by otelcconfig. DO NOT EDIT.\n\npackage baked\n\n"+
		"import \"github.com/ADITYA-CODE-SOURCE/otelcconfig/runtime\"\n\nfunc init() {\n\truntime.Register(runtime.ConfigSnapshot{})\n}\n")
	diags, err := Run([]string{dir})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if len(diags) != 0 {
		t.Fatalf("generated file flagged: %v", diags)
	}
}

func TestRunSkipsTestAndGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	// A violating _test.go must be skipped.
	if err := os.WriteFile(filepath.Join(dir, "hook_test.go"),
		[]byte("package hook\nimport (\n\"os\"\n)\nfunc _() { _ = os.Getenv(\"OTEL_GO_ENABLED_INSTRUMENTATIONS\") }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// A violating _gen.go with a runtime.Register must also be skipped.
	if err := os.WriteFile(filepath.Join(dir, "snapshot_gen.go"),
		[]byte("package hook\nimport \"github.com/ADITYA-CODE-SOURCE/otelcconfig/runtime\"\nfunc init() { runtime.Register(runtime.ConfigSnapshot{}) }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	diags, err := Run([]string{dir})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if len(diags) != 0 {
		t.Fatalf("unexpected diagnostics: %v", diags)
	}
}

