func TestRunAllowsYamlInTooling(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "cmd")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "config.go"),
		[]byte("package cfg\n\nimport \"gopkg.in/yaml.v3\"\n\nvar _ = yaml.Unmarshal\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	diags, err := Run([]string{dir})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if len(diags) != 0 {
		t.Fatalf("yaml import in tooling flagged: %v", diags)
	}
}

func TestRunRepoHooksAreClean(t *testing.T) {
	diags, err := Run([]string{"../../demo", "../../runtime", "../../baked"})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	var msgs []string
	for _, d := range diags {
		msgs = append(msgs, d.Pos.String()+": "+d.Message)
	}
	if len(msgs) != 0 {
		t.Fatalf("repo hook packages violate the contract:\n%s", strings.Join(msgs, "\n"))
	}
}

